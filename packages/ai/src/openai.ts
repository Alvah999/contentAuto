import type { DesignProfile, DesignSpec, NormalizedContent } from "@content-auto/shared";
import { validateDesignSpec } from "@content-auto/design-engine";
import type { AiDesignProvider } from "./provider.js";
import { MockAiDesignProvider } from "./mock.js";

/**
 * OpenAI-backed design spec generator.
 * Falls back to mock layout if the model response fails validation.
 */
export class OpenAiDesignProvider implements AiDesignProvider {
  readonly id = "openai";
  readonly mode = "live" as const;
  private readonly fallback = new MockAiDesignProvider();

  constructor(
    private readonly apiKey: string,
    private readonly model: string,
  ) {}

  async generateDesignSpec(input: {
    content: NormalizedContent;
    profile: DesignProfile;
    jobId: string;
    title?: string;
  }): Promise<DesignSpec> {
    const prompt = buildPrompt(input);
    try {
      const res = await fetch("https://api.openai.com/v1/chat/completions", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${this.apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: this.model,
          temperature: 0.4,
          response_format: { type: "json_object" },
          messages: [
            {
              role: "system",
              content:
                "You are a design specification generator. Return ONLY valid JSON matching the DesignSpec schema. Use logical layer names like Text / Headline, Shape / CTA Button, Frame / Root. Never mutate reference templates.",
            },
            { role: "user", content: prompt },
          ],
        }),
      });

      if (!res.ok) {
        throw new Error(`OpenAI API ${res.status}: ${await res.text()}`);
      }

      const data = (await res.json()) as {
        choices?: Array<{ message?: { content?: string } }>;
      };
      const raw = data.choices?.[0]?.message?.content;
      if (!raw) throw new Error("Empty OpenAI response");

      const parsed = JSON.parse(raw) as unknown;
      const validated = validateDesignSpec(parsed);
      if (!validated.valid || !validated.data) {
        throw new Error(`Schema validation failed: ${validated.errors?.join("; ")}`);
      }

      return {
        ...validated.data,
        id: `spec-${input.jobId}`,
        profileId: input.profile.id,
        contentId: input.content.sourceId,
        createdAt: new Date().toISOString(),
        notes: [
          ...(validated.data.notes ?? []),
          `Generated by OpenAI (${this.model}).`,
        ],
      };
    } catch {
      const fallback = await this.fallback.generateDesignSpec(input);
      return {
        ...fallback,
        notes: [
          ...(fallback.notes ?? []),
          "OpenAI generation failed or invalid; used deterministic mock fallback.",
        ],
      };
    }
  }
}

function buildPrompt(input: {
  content: NormalizedContent;
  profile: DesignProfile;
  jobId: string;
  title?: string;
}): string {
  return JSON.stringify(
    {
      task: "Generate a DesignSpec v1.0",
      jobId: input.jobId,
      title: input.title ?? input.content.title,
      content: input.content,
      profile: input.profile,
      schemaHints: {
        version: "1.0",
        rootType: "FRAME",
        layerTypes: ["FRAME", "RECTANGLE", "TEXT", "ELLIPSE", "LINE"],
        required: ["id", "name", "profileId", "contentId", "canvas", "root", "createdAt"],
      },
    },
    null,
    2,
  );
}
